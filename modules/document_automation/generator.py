"""Generate generic PDF records from CSV files with arbitrary columns."""
import csv
import os
import re
import tempfile
import zipfile

from reportlab.lib.pagesizes import A4
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen import canvas

MAX_LABEL_LENGTH = 100
MAX_VALUE_LENGTH = 2000


def _safe_filename(value, fallback):
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "_", str(value or "")).strip("_")
    return (cleaned[:60] or fallback)


def _draw_wrapped_text(document, text, x, y, max_width, font_name="Helvetica", font_size=10, line_height=14):
    """Draw text with basic word wrapping and page breaks."""
    document.setFont(font_name, font_size)
    words = str(text).split()
    lines = []
    current = ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if current and stringWidth(candidate, font_name, font_size) > max_width:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)

    for line in lines or [""]:
        if y < 65:
            document.showPage()
            y = 790
            document.setFont(font_name, font_size)
        document.drawString(x, y, line[:250])
        y -= line_height
    return y


def generate_customer_pdfs(csv_path, output_folder):
    """Create one generic PDF record per non-empty CSV row.

    The legacy function name is retained so existing workflow integrations
    continue to work. No customer-specific column names are required.
    """
    os.makedirs(output_folder, exist_ok=True)

    with open(csv_path, newline="", encoding="utf-8-sig") as source:
        reader = csv.DictReader(source)
        headers = [
            str(header or "").strip()
            for header in (reader.fieldnames or [])
        ]
        if not headers or not any(headers):
            raise ValueError("CSV must contain a header row with at least one column.")

        # DictReader uses None for surplus fields and overwrites duplicate header
        # names, so reject ambiguous headers rather than silently losing data.
        if any(not header for header in headers):
            raise ValueError("CSV contains an empty column name. Please add a name to every header.")
        if len({header.casefold() for header in headers}) != len(headers):
            raise ValueError("CSV contains duplicate column names. Please make each header unique.")

        rows = list(reader)

    if not rows:
        raise ValueError("CSV contains no data rows.")

    batch_dir = tempfile.mkdtemp(prefix="opspilot_records_")
    pdf_paths = []
    skipped_rows = 0

    for index, row in enumerate(rows, start=1):
        if None in row:
            raise ValueError(
                f"Row {index + 1} contains more values than the header. "
                "Check the CSV delimiter and column count."
            )
        values = {
            header: str(row.get(header) or "").strip()
            for header in headers
        }
        if not any(values.values()):
            skipped_rows += 1
            continue

        first_value = next((value for value in values.values() if value), "")
        record_name = _safe_filename(first_value, f"record_{index:04d}")
        pdf_path = os.path.join(batch_dir, f"record_{index:04d}_{record_name}.pdf")
        document = canvas.Canvas(pdf_path, pagesize=A4)
        document.setTitle(f"Data Record {index}")
        document.setFont("Helvetica-Bold", 18)
        document.drawString(55, 785, f"DATA RECORD {index}")
        y = 745

        for header, value in values.items():
            label = header[:MAX_LABEL_LENGTH]
            rendered_value = value[:MAX_VALUE_LENGTH]
            if len(value) > MAX_VALUE_LENGTH:
                rendered_value += " ... [truncated]"
            document.setFont("Helvetica-Bold", 10)
            document.drawString(55, y, f"{label}:")
            y -= 15
            y = _draw_wrapped_text(
                document,
                rendered_value or "(blank)",
                70,
                y,
                465,
                font_size=10,
            )
            y -= 12

        document.setFont("Helvetica-Oblique", 8)
        document.drawString(55, 40, "Generated by OpsPilot Document Automation")
        document.save()
        pdf_paths.append(pdf_path)

    if not pdf_paths:
        raise ValueError("CSV contains no rows with data.")

    zip_path = os.path.join(output_folder, "customer_documents.zip")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as archive:
        for pdf_path in pdf_paths:
            archive.write(pdf_path, os.path.basename(pdf_path))

    return zip_path, len(pdf_paths)
