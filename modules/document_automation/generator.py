import csv
import os
import re
import tempfile
import zipfile

from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

REQUIRED_COLUMNS = {"customer_name", "customer_id", "email", "plan"}


def generate_customer_pdfs(csv_path, output_folder):
    os.makedirs(output_folder, exist_ok=True)
    with open(csv_path, newline="", encoding="utf-8-sig") as source:
        reader = csv.DictReader(source)
        if not reader.fieldnames or not REQUIRED_COLUMNS.issubset(set(reader.fieldnames)):
            raise ValueError("CSV must contain: customer_name, customer_id, email, plan")
        rows = list(reader)

    if not rows:
        raise ValueError("CSV contains no customer records.")

    batch_dir = tempfile.mkdtemp(prefix="customer_docs_")
    pdf_paths = []

    for index, row in enumerate(rows, start=1):
        name = (row.get("customer_name") or "").strip()
        customer_id = (row.get("customer_id") or "").strip()
        email = (row.get("email") or "").strip()
        plan = (row.get("plan") or "").strip()
        if not name or not customer_id:
            continue

        safe_id = re.sub(r"[^A-Za-z0-9_-]", "_", customer_id)[:60] or str(index)
        pdf_path = os.path.join(batch_dir, f"customer_{index:04d}_{safe_id}.pdf")
        document = canvas.Canvas(pdf_path, pagesize=A4)
        document.setTitle(f"Customer Summary - {customer_id}")
        document.setFont("Helvetica-Bold", 18)
        document.drawString(55, 785, "CUSTOMER SUMMARY")
        document.setFont("Helvetica", 11)
        document.drawString(55, 745, f"Customer name: {name}")
        document.drawString(55, 725, f"Customer ID: {customer_id}")
        document.drawString(55, 705, f"Email: {email}")
        document.drawString(55, 685, f"Plan: {plan}")
        document.setFont("Helvetica-Oblique", 9)
        document.drawString(
            55, 55, "Demo document generated by Business Operations Automation Toolkit."
        )
        document.save()
        pdf_paths.append(pdf_path)

    if not pdf_paths:
        raise ValueError("No valid customer rows found.")

    zip_path = os.path.join(output_folder, "customer_documents.zip")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as archive:
        for pdf_path in pdf_paths:
            archive.write(pdf_path, os.path.basename(pdf_path))

    return zip_path, len(pdf_paths)
